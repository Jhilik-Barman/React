//Arithmetic Operators
// Addition (+),Subtraction (-),Multiplication (*),Division (/),Modulus (%) – Remainder,Exponentiation ()** – Power
console.log(5 + 3); // 8
console.log(10 - 4); // 6
console.log(4 * 2); // 8
console.log(8 / 2); // 4
console.log(7 % 3); // 1
console.log(2 ** 3); // 8


//Assignment Operators
//= (assign value)
let x = 10;
//+= (add and assign)
let a = 5;
a += 3;
//(a=a+3 )// a = 8
//-= (subtract and assign)
let b = 10;
b -= 4; 
//(b=b-4)// b = 6


//Comparison Operators
//==
console.log(5 == "5"); // true
//===
console.log(5 === "5"); // false
//> (greater than)
console.log(8 > 5); // true
//< (less than)
console.log(3 < 6); // true


//Logical Operators
//&& (AND)
console.log(true && false); // false
//|| (OR)
console.log(true || false); // true
//! (NOT)
console.log(!true); // false


//String Operator
console.log("Hello" + " World"); // Hello World

//Increment / Decrement
//x++ (increase by 1)
let p = 5;
p++;
console.log(p); // 6
//x-- (decrease by 1)
let q = 5;
q--;
console.log(q); // 4